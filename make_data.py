import numpy as np, pandas as pd
np.random.seed(42)
dates = pd.date_range("2022-01-01", "2025-12-31", freq="D")
n = len(dates)
t = np.arange(n)
weekend = (dates.dayofweek >= 5).astype(int)
festival = dates.month.isin([10, 11]).astype(int)
promo = (np.random.rand(n) < 0.15).astype(int)
price = np.round(np.random.uniform(90, 110, n), 2)
season = 30 * np.sin(2 * np.pi * (dates.dayofyear - 80) / 365)
sales = 200 + 0.15*t + 40*weekend + 60*festival + 50*promo + season - 2*(price - 100) + np.random.normal(0, 12, n)
df = pd.DataFrame({"date": dates, "sales": sales.round(1), "price": price, "promo": promo, "festival": festival, "weekend": weekend})
df.to_csv("sales.csv", index=False)
print(df.head())
print("Rows:", len(df))